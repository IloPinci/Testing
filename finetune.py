"""
finetune.py
-----------
Fine-tunes SmolVLA on a LeRobot v3.0 dataset produced by oracle_direct.py.

Usage:
    python finetune.py \
        --dataset_dir  demos/lerobot/ \
        --repo_id      local/genesis_pickplace \
        --out_dir      outputs/train/smolvla_genesis/ \
        --steps        20000 \
        --batch_size   64 \
        --seed         0

What this script does:
  1. Validates that dataset_dir contains a v3.0 info.json (codebase_version v3.0).
  2. Builds and streams the lerobot-train command (lerobot 0.5.x CLI).
  3. Saves finetune_run.json with full run metadata, including the training
     seed and the dataset's own generation seed (read from
     demos/.../generation_manifest.json if present), so a single checkpoint's
     provenance is fully reconstructable (M8, ST5).

LeRobot 0.5.x training CLI:
    lerobot-train \
        --policy.path=lerobot/smolvla_base \
        --dataset.repo_id=<repo_id> \
        --dataset.root=<local_path>  ← avoids Hub download for local datasets \
        --batch_size=64 \
        --steps=20000 \
        --output_dir=<out_dir> \
        --policy.device=cuda \
        --seed=<seed>

Key flags:
    --dataset.root   tells the trainer to use local files instead of downloading
                     from the Hub; set to the same path as --dataset_dir.
    --policy.path    the base checkpoint; fine-tuned weights override the head.
    --seed           training-run RNG seed (batch shuffling, weight init of any
                     newly-initialized heads, dropout, etc). Distinct from the
                     dataset-generation seed recorded in generation_manifest.json
                     and from the env/rollout seed used later in
                     zeroshot_eval.py (ST5: keep all three separate).

NOTE: verify --seed is actually a supported lerobot-train flag for your
installed lerobot version before relying on it (`lerobot-train --help`).
If it isn't, this script still records --seed in finetune_run.json as the
intended training seed and prints a warning that it could not be passed
through to the trainer itself — do not silently claim seed control you
don't have.
"""

import argparse
import json
import subprocess
import sys
import time
from datetime import datetime
from pathlib import Path


# ══════════════════════════════════════════════════════════════════════════════
#  Helpers
# ══════════════════════════════════════════════════════════════════════════════

def validate_dataset(dataset_dir: Path):
    """Check that dataset_dir is a valid LeRobot v3.0 dataset."""
    info_path = dataset_dir / "meta" / "info.json"
    if not info_path.exists():
        print(f"[error] {info_path} not found.")
        print("        Make sure oracle_direct.py ran successfully and called finalize().")
        sys.exit(1)

    with open(info_path) as f:
        info = json.load(f)

    version = info.get("codebase_version", "unknown")
    n_eps   = info.get("total_episodes", 0)
    fps     = info.get("fps", "?")

    if not version.startswith("v3"):
        print(f"[warn] Dataset version is '{version}', expected 'v3.x'.")
        print("       If you have a v2.1 dataset, run:")
        print("         python -m lerobot.datasets.v30.convert_dataset_v21_to_v30 --repo-id=...")

    print(f"[ok] Dataset v{version}: {n_eps} episodes at {fps} fps")
    cam_keys = [k for k in info.get("features", {}) if "images" in k]
    print(f"     Cameras : {cam_keys}")
    print(f"     Task    : {info.get('tasks', ['?'])[0]}")

    if n_eps < 50:
        print(f"\n[warn] Only {n_eps} episodes — SmolVLA recommends ≥50 for reliable performance.")
        print("       Consider collecting more before fine-tuning.")

    return info


def read_generation_manifest(dataset_dir: Path) -> dict | None:
    """
    Read the dataset-generation manifest written by oracle_direct.py's
    collect_demonstrations(), if present, so finetune_run.json can record
    the FULL provenance chain: dataset-gen seed -> training seed -> (later)
    env/rollout seed in zeroshot_eval.py. Returns None for datasets
    generated before this manifest existed.
    """
    manifest_path = dataset_dir / "generation_manifest.json"
    if not manifest_path.exists():
        print(f"[warn] No generation_manifest.json found at {manifest_path} — "
              f"this dataset predates seed tracking, or was generated by an "
              f"older version of oracle_direct.py. Its generation seed is "
              f"unknown and cannot be recorded in finetune_run.json.")
        return None
    try:
        return json.loads(manifest_path.read_text())
    except Exception as e:
        print(f"[warn] Could not parse {manifest_path}: {e}")
        return None


def find_last_checkpoint(out_dir: Path) -> Path | None:
    """Return the pretrained_model dir of the last saved checkpoint."""
    last = out_dir / "checkpoints" / "last" / "pretrained_model"
    if last.exists():
        return last
    ckpt_dirs = sorted((out_dir / "checkpoints").glob("*/pretrained_model"))
    return ckpt_dirs[-1] if ckpt_dirs else None


def build_command(args, dataset_dir: Path) -> list[str]:
    """
    Build the lerobot-train command for lerobot 0.5.x.

    The CLI uses argparse-style --key value flags (NOT draccus key=value).
    --dataset.root tells the trainer to load from disk, not the Hub.
    """
    device = "cpu" if args.cpu else "cuda"

    cmd = [
        "lerobot-train",
        f"--policy.path=lerobot/smolvla_base",
        f"--dataset.repo_id={args.repo_id}",
        f"--dataset.root={dataset_dir}",      # ← local v3.0 root, skips Hub download
        f"--batch_size={args.batch_size}",
        f"--steps={args.steps}",
        f"--output_dir={args.out_dir}",
        f"--job_name=smolvla_genesis_finetune",
        f"--policy.device={device}",
        f"--save_freq={args.save_freq}",
        f"--wandb.enable={'true' if args.wandb else 'false'}",
        f"--policy.push_to_hub=false",
    ]

    if args.seed is not None:
        cmd.append(f"--seed={args.seed}")

    if args.wandb and args.wandb_project:
        cmd.append(f"--wandb.project={args.wandb_project}")

    if args.resume:
        cmd.append("--resume=true")

    return cmd


# ══════════════════════════════════════════════════════════════════════════════
#  Main
# ══════════════════════════════════════════════════════════════════════════════

def main():
    parser = argparse.ArgumentParser(
        description="Fine-tune SmolVLA on a local LeRobot v3.0 dataset."
    )
    parser.add_argument("--dataset_dir",   default="demos/lerobot/",
                        help="Local LeRobot v3.0 dataset (output of oracle_direct.py)")
    parser.add_argument("--repo_id",       default="local/genesis_pickplace",
                        help="Must match the repo_id used during collection")
    parser.add_argument("--out_dir",       default=None,
                        help="Explicit checkpoint/log directory. Either this OR "
                             "--run_root is required. --out_dir wins if both given.")
    parser.add_argument("--run_root", default=None,
                        help="Short campaign tag, e.g. 'icra-final'. Derives "
                             "the checkpoint dir as runs/<run_root>/train/"
                             "<checkpoint_id>/ (see run_naming.py).")
    parser.add_argument("--checkpoint_id", default="checkpoint",
                        help="Short label for this checkpoint when using "
                             "--run_root (e.g. 'seed0', 'seed1').")
    parser.add_argument("--overwrite", action="store_true",
                        help="Allow writing into an already-populated out_dir. "
                             "Ignored (always allowed) when --resume is set, "
                             "since resuming is explicitly meant to reuse the dir.")
    parser.add_argument("--steps",         type=int, default=20000)
    parser.add_argument("--batch_size",    type=int, default=64,
                        help="64 fits on an A100; reduce to 16–32 for smaller GPUs")
    parser.add_argument("--save_freq",     type=int, default=5000)
    parser.add_argument("--seed",          type=int, default=None,
                        help="Training-run RNG seed (ST5/S4/M8). REQUIRED for "
                             "any checkpoint you intend to report as a distinct "
                             "'seed N' in a multi-seed replication — passed to "
                             "lerobot-train's --seed flag if supported by your "
                             "installed version (verify with `lerobot-train "
                             "--help`), and always recorded in finetune_run.json "
                             "regardless.")
    parser.add_argument("--wandb",         action="store_true")
    parser.add_argument("--wandb_project", default="smolvla_genesis")
    parser.add_argument("--cpu",           action="store_true",
                        help="Force CPU — very slow, for debugging only")
    parser.add_argument("--resume",        action="store_true")
    args = parser.parse_args()

    if args.out_dir is None and args.run_root is None:
        print("[error] Either --out_dir or --run_root is required.")
        sys.exit(1)

    if args.seed is None:
        print("[warn] --seed not set for this fine-tuning run. If you plan to "
              "report multiple independently-trained checkpoints (S4), every "
              "one of them needs an explicit, distinct --seed or the "
              "replication claim has no basis.")

    dataset_dir = Path(args.dataset_dir).resolve()

    if args.out_dir is not None:
        out_dir = Path(args.out_dir)
    else:
        from run_naming import run_root as _run_root, train_dir
        root    = _run_root(args.run_root)
        out_dir = train_dir(root, args.checkpoint_id)
        print(f"[run_root] {args.run_root} -> checkpoint_id '{args.checkpoint_id}' -> {out_dir}")

    # CRITICAL: build_command() reads args.out_dir, not the local out_dir
    # variable above. Without this line, a --run_root-derived path never
    # reaches the actual lerobot-train invocation — it launches with
    # --output_dir=None (the literal, un-derived default), silently
    # checkpointing somewhere else entirely while this script's own
    # bookkeeping (refuse_if_exists, finetune_run.json) all reference the
    # CORRECT runs/<tag>/train/<id>/ path. This exact bug shipped once;
    # do not remove this line.
    args.out_dir = str(out_dir)

    if not args.resume:
        from run_naming import refuse_if_exists
        refuse_if_exists(out_dir, "Checkpoint/log directory", args.overwrite)

    # ── Validate ──────────────────────────────────────────────────────────────
    info = validate_dataset(dataset_dir)
    generation_manifest = read_generation_manifest(dataset_dir)

    # ── Build command ─────────────────────────────────────────────────────────
    cmd = build_command(args, dataset_dir)

    print(f"\n── Training command ──────────────────────────────────────")
    print("  " + " \\\n    ".join(cmd))
    print(f"─────────────────────────────────────────────────────────\n")


    # ── Launch ────────────────────────────────────────────────────────────────
    print("[info] Launching lerobot-train …\n")
    started_at_iso = datetime.now().isoformat()   # captured BEFORE the subprocess,
    t0             = time.time()                   # so "started_at" in the JSON below
                                                     # actually means what it says —
                                                     # previously this was captured
                                                     # AFTER proc.wait(), making every
                                                     # run's logged start time land
                                                     # seconds before its finish time
                                                     # regardless of true duration.
    proc = subprocess.Popen(
        cmd,
        stdout=subprocess.PIPE,
        stderr=subprocess.STDOUT,
        text=True,
        bufsize=1,
    )

    log_lines = []
    seed_flag_rejected = False
    for line in proc.stdout:
        print(line, end="", flush=True)
        log_lines.append(line)
        # Best-effort detection of an unsupported --seed flag, so we can warn
        # rather than silently claim seed control we didn't actually get.
        if args.seed is not None and "seed" in line.lower() and (
            "unrecognized" in line.lower() or "unexpected" in line.lower()
        ):
            seed_flag_rejected = True

    proc.wait()
    elapsed = time.time() - t0

    if seed_flag_rejected:
        print(f"\n[warn] --seed may not be a recognized lerobot-train flag for "
              f"your installed lerobot version — check the log above. "
              f"finetune_run.json will still record the INTENDED seed "
              f"({args.seed}), but training may not actually have been "
              f"seeded. Verify with `lerobot-train --help` before reporting "
              f"this as a controlled-seed run.")

    # ── Write pending run metadata ────────────────────────────────────────────
    out_dir.mkdir(parents=True, exist_ok=True)
    run_meta = {
        "started_at":               started_at_iso,
        "dataset_dir":               str(dataset_dir),
        "repo_id":                   args.repo_id,
        "out_dir":                   str(out_dir.resolve()),
        "steps":                     args.steps,
        "batch_size":                args.batch_size,
        "save_freq":                 args.save_freq,
        "train_seed":                args.seed,
        "train_seed_flag_rejected":  seed_flag_rejected,
        "dataset_generation_seed":   (generation_manifest or {}).get("seed"),
        "dataset_generation_manifest_found": generation_manifest is not None,
        "base_checkpoint":           "lerobot/smolvla_base",
        "n_episodes":                info.get("total_episodes"),
        "fps":                       info.get("fps"),
        "dataset_version":           info.get("codebase_version"),
        "wandb":                     args.wandb,
        "command":                   " ".join(cmd),
        "status":                    "running",
        "finished_at":               None,
        "return_code":               None,
        "last_checkpoint":           None,
    }


    # ── Save log ──────────────────────────────────────────────────────────────
    log_path = out_dir / "train_log.txt"
    with open(log_path, "w") as f:
        f.writelines(log_lines)
    print(f"\n[ok] Training log → {log_path}")

    # ── Finalise metadata ─────────────────────────────────────────────────────
    final_path = out_dir / "finetune_run.json"
    last_ckpt = find_last_checkpoint(out_dir)

    run_meta.update({
        "finished_at":     datetime.now().isoformat(),
        "return_code":     proc.returncode,
        "elapsed_seconds": round(elapsed, 1),
        "status":          "ok" if proc.returncode == 0 else "failed",
        "last_checkpoint": str(last_ckpt) if last_ckpt else None,
    })
    with open(final_path, "w") as f:
        json.dump(run_meta, f, indent=2)

    # ── Summary ───────────────────────────────────────────────────────────────
    status = "SUCCESS ✓" if proc.returncode == 0 else "FAILED ✗"
    print(f"\n── Fine-tuning summary ───────────────────────────────────")
    print(f"  Status               : {status}")
    print(f"  Elapsed              : {elapsed / 60:.1f} min")
    print(f"  Train seed           : {args.seed}"
          f"{'  [FLAG MAY NOT BE SUPPORTED — see warning above]' if seed_flag_rejected else ''}")
    print(f"  Dataset-gen seed     : {run_meta['dataset_generation_seed']}")
    print(f"  Last checkpoint      : {last_ckpt}")
    print(f"  Run metadata         : {final_path}")
    print(f"─────────────────────────────────────────────────────────")

    if proc.returncode != 0:
        print(f"\n[error] Training failed (exit code {proc.returncode}).")
        print(f"        Full log: {log_path}")
        sys.exit(proc.returncode)

    print(f"\n[next] Evaluate the fine-tuned model:")
    print(f"       python zeroshot_eval.py --checkpoint {last_ckpt} \\")
    print(f"           --checkpoint_id <label> --train_seed {args.seed} \\")
    print(f"           --run_root <same tag used above> --n 100 \\")
    print(f"           --matched_eval_set runs/<run_root>/matched_eval_set.json")


if __name__ == "__main__":
    main()